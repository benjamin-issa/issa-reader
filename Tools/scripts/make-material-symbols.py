#!/usr/bin/env python3
"""Generate the Android app's icons from Material Symbols Rounded.

The Apple apps draw SF Symbols, which Apple licenses for its own platforms
only. Android uses Google's Material Symbols (Apache-2.0) in the Rounded style,
one counterpart per SF Symbol, mapped in `Android/ui/symbols.json`. This writes
a vector drawable per Material symbol into `Android/ui/src/main/res/drawable/`
and `Symbols.kt`, which names each drawable after the SF Symbol the Swift code
uses, so a port reads `Symbols.booksVertical` where Swift says
`"books.vertical"`.

    npm pack @material-symbols/svg-400 && tar -xzf material-symbols-svg-400-*.tgz
    python3 Tools/scripts/make-material-symbols.py package/rounded

The output is committed; run this only when the mapping changes.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UI = ROOT / "Android" / "ui"
DRAWABLES = UI / "src" / "main" / "res" / "drawable"
KOTLIN = UI / "src" / "main" / "kotlin" / "com" / "benjaminissa" / "issareader" / "ui" / "Symbols.kt"


def drawable_name(material: str, fill: bool) -> str:
    return "ms_" + material + ("_fill" if fill else "")


def vector(svg: str) -> str:
    """One Material symbol as an Android vector drawable.

    Material's SVGs use a 960-unit viewBox whose origin is at the bottom
    (`0 -960 960 960`), so the paths are moved down by 960 inside a group.
    Drawn in black and tinted at the call site, like an SF Symbol.
    """
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if not paths:
        raise ValueError("no path")
    body = "\n".join(
        f'        <path android:fillColor="#FF000000" android:pathData="{d}" />' for d in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by Tools/scripts/make-material-symbols.py from Material Symbols Rounded (Apache-2.0). -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        '    android:viewportWidth="960"\n'
        '    android:viewportHeight="960">\n'
        '    <group android:translateY="960">\n'
        f"{body}\n"
        "    </group>\n"
        "</vector>\n"
    )


def kotlin_name(sf: str) -> str:
    parts = re.split(r"[.]", sf)
    head, *rest = parts
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = Path(sys.argv[1])
    mapping = {k: v for k, v in json.loads((UI / "symbols.json").read_text()).items() if not k.startswith("_")}
    DRAWABLES.mkdir(parents=True, exist_ok=True)
    for old in DRAWABLES.glob("ms_*.xml"):
        old.unlink()
    written = set()
    for sf, (material, fill) in sorted(mapping.items()):
        name = drawable_name(material, fill)
        if name in written:
            continue
        svg = (source / f"{material}{'-fill' if fill else ''}.svg").read_text()
        (DRAWABLES / f"{name}.xml").write_text(vector(svg))
        written.add(name)
    lines = [
        "package com.benjaminissa.issareader.ui",
        "",
        "import androidx.annotation.DrawableRes",
        "",
        "/**",
        " * The app's icons, named after the SF Symbol the Swift code draws, each a",
        " * Material Symbols Rounded counterpart (`Android/ui/symbols.json`).",
        " *",
        " * Generated by `Tools/scripts/make-material-symbols.py`; edit the mapping and",
        " * regenerate rather than editing this file.",
        " */",
        "object Symbols {",
    ]
    for sf, (material, fill) in sorted(mapping.items()):
        lines.append(f"    /** `{sf}` */")
        lines.append(f"    @DrawableRes val {kotlin_name(sf)}: Int = R.drawable.{drawable_name(material, fill)}")
    lines.append("}")
    KOTLIN.write_text("\n".join(lines) + "\n")
    print(f"{len(written)} drawables, {len(mapping)} symbols")


if __name__ == "__main__":
    main()

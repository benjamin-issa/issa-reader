#!/usr/bin/env python3
"""Draws the Issa Reader icon for Android: the launcher's adaptive icon, and the
512 px icon Google Play shows.

The same mark as every other platform — design 2d, "book & headphones" — from
the same geometry (`icon_mark.py`, `Tools/design/app-icon/ICON.md`).

An Android launcher icon is an adaptive icon: a background layer (the slate),
a foreground layer (the mark) and a monochrome layer for themed icons, each
108 dp square, of which the launcher shows the middle 72 dp through a mask of
its own choosing. So the 180-unit design square is mapped onto that visible
72 dp, which puts the whole mark inside the 66 dp every mask keeps. The
layers are vector drawables written from the geometry, so they are crisp at
every density; the Play icon is drawn with Pillow like the Apple icons, full
bleed, because Play rounds its own corners.

The monochrome layer is the book and headphones in one colour; the launcher
tints it. The spine is left out, so the gap between the pages draws it.

Usage: make-android-icon.py
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from icon_mark import ART_SHIFT_Y, BAND_CENTRE, BAND_R, BAND_W, CUP_R, CUPS, SPINE, VARIANTS, _LEFT, _RIGHT, render

REPO = pathlib.Path(__file__).resolve().parents[2]
RES = REPO / "Android/app/src/main/res"
PLAY = REPO / "Android/app/play"

# 108 dp drawn on a 270-unit viewport: 1 unit = 0.4 dp, so the 180-unit design
# square spans the 72 dp the launcher shows, starting 45 units in.
VIEWPORT = 270
INSET = (VIEWPORT - 180) / 2


def hexcolour(rgb):
    return "#FF%02X%02X%02X" % rgb


def page_path(curves):
    (p0, c1, c2, p3), (q0, d1, d2, q3) = curves
    f = lambda p: f"{p[0]:g},{p[1]:g}"
    return f"M{f(p0)} C{f(c1)} {f(c2)} {f(p3)} L{f(q0)} C{f(d1)} {f(d2)} {f(q3)} Z"


def cup_path(box, r):
    x0, y0, x1, y1 = box
    return (
        f"M{x0 + r:g},{y0:g} H{x1 - r:g} A{r:g},{r:g} 0 0 1 {x1:g},{y0 + r:g} "
        f"V{y1 - r:g} A{r:g},{r:g} 0 0 1 {x1 - r:g},{y1:g} H{x0 + r:g} "
        f"A{r:g},{r:g} 0 0 1 {x0:g},{y1 - r:g} V{y0 + r:g} A{r:g},{r:g} 0 0 1 {x0 + r:g},{y0:g} Z"
    )


def band_path():
    cx, cy = BAND_CENTRE
    return f"M{cx - BAND_R:g},{cy:g} A{BAND_R:g},{BAND_R:g} 0 0 1 {cx + BAND_R:g},{cy:g}"


def vector(paths, comment):
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by Tools/scripts/make-android-icon.py; edit the geometry there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="{VIEWPORT}"
    android:viewportHeight="{VIEWPORT}">
    <group android:translateX="{INSET:g}" android:translateY="{INSET + ART_SHIFT_Y:g}">
{body}
    </group>
</vector>
"""


def fill(d, colour):
    return f'        <path android:fillColor="{colour}" android:pathData="{d}" />'


def stroke(d, colour, width, cap="butt"):
    return (f'        <path android:strokeColor="{colour}" android:strokeWidth="{width:g}" '
            f'android:strokeLineCap="{cap}" android:pathData="{d}" />')


def main():
    c = VARIANTS["default"]
    x0, y0, x1, y1 = SPINE
    spine = f"M{(x0 + x1) / 2:g},{y0:g} V{y1:g}"
    foreground = [
        fill(page_path(_LEFT), hexcolour(c["page_left"])),
        fill(page_path(_RIGHT), hexcolour(c["page_right"])),
        stroke(spine, hexcolour(c["spine"]), x1 - x0),
        stroke(band_path(), hexcolour(c["band"]), BAND_W, "round"),
    ] + [fill(cup_path(box, CUP_R), hexcolour(c["band"])) for box in CUPS]
    monochrome = [
        fill(page_path(_LEFT), "#FF000000"),
        fill(page_path(_RIGHT), "#FF000000"),
        stroke(band_path(), "#FF000000", BAND_W, "round"),
    ] + [fill(cup_path(box, CUP_R), "#FF000000") for box in CUPS]

    drawable = RES / "drawable"
    drawable.mkdir(parents=True, exist_ok=True)
    (drawable / "ic_launcher_foreground.xml").write_text(vector(foreground, "The mark, on the adaptive icon's foreground layer."))
    (drawable / "ic_launcher_monochrome.xml").write_text(vector(monochrome, "The mark in one colour, for themed icons."))

    values = RES / "values"
    values.mkdir(parents=True, exist_ok=True)
    (values / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by Tools/scripts/make-android-icon.py. The icon's slate, Palette.slate. -->\n"
        f'<resources>\n    <color name="ic_launcher_background">{"#%02X%02X%02X" % c["bg"]}</color>\n</resources>\n'
    )

    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by Tools/scripts/make-android-icon.py. -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    mipmap = RES / "mipmap-anydpi"
    mipmap.mkdir(parents=True, exist_ok=True)
    (mipmap / "ic_launcher.xml").write_text(adaptive)
    (mipmap / "ic_launcher_round.xml").write_text(adaptive)

    PLAY.mkdir(parents=True, exist_ok=True)
    render(512, 512, VARIANTS["default"]).save(PLAY / "icon-512.png")
    print("wrote the adaptive icon layers and", (PLAY / "icon-512.png").relative_to(REPO))


if __name__ == "__main__":
    main()
